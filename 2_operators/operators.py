# Arithmetic Operators
x = 10
y = 5

print(x + y)
print(x - y)
print(x * y)
print(x / y)
print(x % y)
print(x**y)

# Comperison Operators
print("Comperison Operators")
print(x == y)
print(x >= y)

# Logical Operators
print("Logical Operators")
print(x > y and x < y)
print(x > y or x < y)
print(not (x < y))
